const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('kaca', {
  cloudStatus: () => ipcRenderer.invoke('cloud:status'),
  assertCloudLicense: () => ipcRenderer.invoke('cloud:assert-license'),
  activateCloudLicense: data => ipcRenderer.invoke('cloud:activate', data),
  openCloudActivation: () => ipcRenderer.invoke('cloud:open-activation'),
  stopCloudRemote: () => ipcRenderer.invoke('cloud:stop-remote'),
  syncCloudNow: () => ipcRenderer.invoke('cloud:sync-now'),
  cloudShareThumbnails: enabled => ipcRenderer.invoke('cloud:share-thumbnails', enabled),
  onCloudSettingsUpdated: cb => {const fn=()=>cb();ipcRenderer.on('cloud:settings-updated',fn);return ()=>ipcRenderer.removeListener('cloud:settings-updated',fn)},
  onCloudDashboard: cb => {const fn=()=>cb();ipcRenderer.on('cloud:open-dashboard',fn);return ()=>ipcRenderer.removeListener('cloud:open-dashboard',fn)},
  readSettings: () => ipcRenderer.invoke('settings:read'),
  writeSettings: value => ipcRenderer.invoke('settings:write', value),
  readEvents: () => ipcRenderer.invoke('events:read'),
  writeEvents: value => ipcRenderer.invoke('events:write', value),
  version: () => ipcRenderer.invoke('app:version'),
  toggleFullscreen: () => ipcRenderer.invoke('window:fullscreen-toggle'),
  isFullscreen: () => ipcRenderer.invoke('window:fullscreen-get'),
  onFullscreenChange: callback => { const listener = (_event, value) => callback(Boolean(value)); ipcRenderer.on('window:fullscreen-changed', listener); return () => ipcRenderer.removeListener('window:fullscreen-changed', listener); },
  readAppLogs: () => ipcRenderer.invoke('app:logs-read'),
  openAppLogs: () => ipcRenderer.invoke('app:logs-open'),
  clearAppLogs: () => ipcRenderer.invoke('app:logs-clear'),
  reportRendererError: entry => ipcRenderer.send('app:renderer-log', entry),
  cameraOsStatus: () => ipcRenderer.invoke('camera:os-status'),
  chooseDashboardAssets: kind => ipcRenderer.invoke('dashboard:choose-assets', kind),
  chooseStorageFolder: () => ipcRenderer.invoke('storage:choose-folder'),
  openPrinterProperties: name => ipcRenderer.invoke('printer:open-properties', name),
  openQrisCheckout: url => ipcRenderer.invoke('payment:open-checkout', url),
  closeQrisCheckout: () => ipcRenderer.invoke('payment:close-checkout'),
  openExternal: url => ipcRenderer.invoke('external:open', url)
});
